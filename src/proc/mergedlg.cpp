MergeDlg::MergeDlg(Git git, const QString& initialRefName, QWidget *parent)
    : QDialog(parent)
    , m_git(std::move(git))
    , m_currentBranch(new QLineEdit(this))
    , m_chooseVersion(new ChooseVersion(m_git, i18n("From"), this))
    , m_squash(new QCheckBox(i18n("&Squash"), this))
    , m_log(new QCheckBox(i18n("Messages"), this))
    , m_logNum(new QSpinBox(this))
    , m_noFF(new QCheckBox(i18n("No &Fast Forward"), this))
    , m_ffOnly(new QCheckBox(i18n("Fast Forward O&nly"), this))
    , m_noCommit(new QCheckBox(i18n("No Co&mmit"), this))
    , m_strategy(new QComboBox(this))
    , m_strategyOption(new QComboBox(this))
    , m_strategyParam(new QLineEdit(this))
    , m_message(new QPlainTextEdit(this))
    , m_buttons(new QDialogButtonBox(QDialogButtonBox::Ok | QDialogButtonBox::Cancel, this))
{
    // CAppUtils::SetWindowTitle
    setWindowTitle(i18nc("@title:window %1 is a folder", "%1 - Merge", QDir::toNativeSeparators(m_git.workingDirectory())));

    auto *layout = new QVBoxLayout(this);

    auto *currentBranchRow = new QHBoxLayout;
    currentBranchRow->addWidget(new QLabel(i18n("Current branch:"), this));
    m_currentBranch->setReadOnly(true);
    m_currentBranch->setFrame(false);
    currentBranchRow->addWidget(m_currentBranch, 1);
    layout->addLayout(currentBranchRow);

    layout->addWidget(m_chooseVersion);

    auto *optionGroup = new QGroupBox(i18n("Option"), this);
    auto *optionLayout = new QGridLayout(optionGroup);
    m_logNum->setRange(0, std::numeric_limits<int>::max());
    auto *logRow = new QHBoxLayout;
    logRow->addWidget(m_log);
    logRow->addWidget(m_logNum);
    logRow->addStretch();
    optionLayout->addWidget(m_squash, 0, 0);
    optionLayout->addLayout(logRow, 0, 1);
    optionLayout->addWidget(m_noFF, 1, 0);
    optionLayout->addWidget(m_ffOnly, 1, 1);
    optionLayout->addWidget(m_noCommit, 2, 0);
    auto *strategyRow = new QHBoxLayout;
    strategyRow->addWidget(new QLabel(i18n("Strategy"), optionGroup));
    strategyRow->addWidget(m_strategy);
    strategyRow->addWidget(m_strategyOption);
    strategyRow->addWidget(m_strategyParam);
    strategyRow->addStretch();
    optionLayout->addLayout(strategyRow, 3, 0, 1, 2);
    optionLayout->setColumnStretch(1, 1);
    layout->addWidget(optionGroup);

    auto *messageGroup = new QGroupBox(i18n("Merge &Message"), this);
    auto *messageLayout = new QVBoxLayout(messageGroup);
    messageLayout->addWidget(m_message);
    layout->addWidget(messageGroup, 1);

    connect(m_buttons, &QDialogButtonBox::accepted, this, &MergeDlg::accept);
    connect(m_buttons, &QDialogButtonBox::rejected, this, &QDialog::reject);
    layout->addWidget(m_buttons);

    // OnInitDialog
    m_message->setPlainText(autoGeneratedText());

    m_strategy->addItems({QStringLiteral("resolve"), recursiveStrategy, QStringLiteral("ours"), QStringLiteral("subtree")});
    m_strategy->setCurrentIndex(-1);
    m_strategyOption->addItems({QStringLiteral("ours"),
                                QStringLiteral("theirs"),
                                QStringLiteral("patience"),
                                QStringLiteral("ignore-space-change"),
                                QStringLiteral("ignore-all-space"),
                                QStringLiteral("ignore-space-at-eol"),
                                QStringLiteral("renormalize"),
                                QStringLiteral("no-renormalize"),
                                QStringLiteral("rename-threshold"),
                                QStringLiteral("subtree")});
    m_strategyOption->setCurrentIndex(-1);

    // The constructor: merge.log's count, if it gives one
    const int configLog = m_git.configValue(QStringLiteral("merge.log")).toInt();
    m_logNum->setValue(configLog > 0 ? configLog : defaultLogCount);

    connect(m_squash, &QCheckBox::toggled, this, &MergeDlg::updateStates);
    connect(m_log, &QCheckBox::toggled, this, &MergeDlg::updateStates);
    connect(m_noFF, &QCheckBox::toggled, this, &MergeDlg::updateStates);
    connect(m_ffOnly, &QCheckBox::toggled, this, &MergeDlg::updateStates);
    connect(m_strategy, &QComboBox::currentTextChanged, this, &MergeDlg::updateStates);
    connect(m_strategyOption, &QComboBox::currentTextChanged, this, &MergeDlg::updateStates);
    updateStates();

    // InitChooseVersion disables OK until the branches and tags are in
    m_buttons->button(QDialogButtonBox::Ok)->setEnabled(false);
    connect(m_chooseVersion, &ChooseVersion::loaded, this, [this] {
        m_currentBranch->setText(m_chooseVersion->currentBranch());
        m_buttons->button(QDialogButtonBox::Ok)->setEnabled(true);
    });
    m_chooseVersion->setSkipCurrentBranch(true);
    m_chooseVersion->setInitialRefName(initialRefName.isEmpty() ? defaultInitialRefName() : initialRefName);
    m_chooseVersion->init(true);

    resize(560, sizeHint().height());
}

const MergeOptions& MergeDlg::options() const
{
    return m_options;
}

ChooseVersion *MergeDlg::chooseVersion() const
{
    return m_chooseVersion;
}

void MergeDlg::accept()
{
    const QString versionName = m_chooseVersion->versionName();
    if (m_chooseVersion->isBranchEmpty()) {
        KMessageBox::error(this, i18n("Branch/Tag name must not be empty or is invalid."), QString(), KMessageBox::Options());
        return;
    }

    QString message = m_message->toPlainText();
    if (message == autoGeneratedText()) {
        message.clear();
    }

    // Only "recursive" takes an option, and only some options a parameter
    const QString strategy = m_strategy->currentText();
    const QString strategyOption = strategy == recursiveStrategy ? m_strategyOption->currentText() : QString();
    const QString strategyParam = optionTakesParam(strategyOption) ? m_strategyParam->text() : QString();

    m_options = MergeOptions{
        .version = versionName,
        .isBranch = m_chooseVersion->isBranch(),
        .noFF = m_noFF->isChecked(),
        .ffOnly = m_ffOnly->isChecked(),
        .squash = m_squash->isChecked(),
        .noCommit = m_noCommit->isChecked(),
        .log = m_log->isChecked() ? std::optional(m_logNum->value()) : std::nullopt,
        .unrelated = false,
        .strategy = strategy,
        .strategyOption = strategyOption,
        .strategyParam = strategyParam,
        .message = message,
    };
    QDialog::accept();
}

void MergeDlg::updateStates()
{
    // OnBnClickedCheckSquash, OnBnClickedCheckFFonlyOrNoFF, OnBnClickedCheckMergeLog and the strategy handlers
    m_message->setEnabled(!m_squash->isChecked());
    m_noFF->setEnabled(!m_squash->isChecked() && !m_ffOnly->isChecked());
    m_ffOnly->setEnabled(!m_noFF->isChecked());
    m_squash->setEnabled(!m_noFF->isChecked());
    m_logNum->setEnabled(m_log->isChecked());
    const bool recursive = m_strategy->currentText() == recursiveStrategy;
    m_strategyOption->setEnabled(recursive);
    m_strategyParam->setEnabled(recursive && optionTakesParam(m_strategyOption->currentText()));
}

QString MergeDlg::defaultInitialRefName() const
{
    // OnInitDialog: the current branch's push branch (CGit::GetRemotePushBranch), if it has one
    const QString currentBranch = GitAdminDir::currentBranchFromFile(GitAdminDir::worktreeAdminDirPath(m_git.workingDirectory()));
    if (currentBranch.isEmpty() || currentBranch == QLatin1String("HEAD")) {
        return {};
    }
    QString pushRemote = m_git.configValue(QStringLiteral("branch.%1.pushremote").arg(currentBranch));
    if (pushRemote.isEmpty()) {
        pushRemote = m_git.configValue(QStringLiteral("remote.pushdefault"));
    }
    if (pushRemote.isEmpty()) {
        pushRemote = m_git.configValue(QStringLiteral("branch.%1.remote").arg(currentBranch));
    }
    // branch.<name>.pushbranch is not stripped (for gerrit, TortoiseGit issue #1609)
    QString pushBranch = m_git.configValue(QStringLiteral("branch.%1.pushbranch").arg(currentBranch));
    if (pushBranch.isEmpty()) {
        pushBranch = Git::stripRefName(m_git.configValue(QStringLiteral("branch.%1.merge").arg(currentBranch)));
    }
    if (pushRemote.isEmpty() || pushBranch.isEmpty()) {
        return {};
    }
    return QStringLiteral("remotes/%1/%2").arg(pushRemote, pushBranch);
}

