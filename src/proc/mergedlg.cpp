using namespace Qt::StringLiterals;

constexpr auto recursiveStrategy = "recursive"_L1;
// CMergeDlg's m_nLog when merge.log doesn't give a count
constexpr int defaultLogCount = 20;

/**
 * @returns IDS_PROC_AUTOGENERATEDBYGIT, the message text that leaves the message to git.
 */
QString autoGeneratedText()
{
    return i18n("<Auto Generated by Git>");
}

/**
 * @param option A --strategy-option value.
 * @returns Whether it takes a parameter: OnCbnSelchangeComboStrategyoption's condition.
 */
bool optionTakesParam(const QString& option)
{
    return option == QLatin1String("rename-threshold") || option == QLatin1String("subtree");
}

